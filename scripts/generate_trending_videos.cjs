function applyRollingTimestampsToVideos(videos, baseTime = Date.now()) {
  return videos.map((v) => {
    let publishedAt;
    if (v.target_periods && v.target_periods.includes('24h')) {
      const offH = v.offset_hours || 4;
      publishedAt = new Date(baseTime - offH * 3600 * 1000).toISOString();
    } else if (v.target_periods && v.target_periods.includes('7d')) {
      const offD = v.offset_days || 3;
      publishedAt = new Date(baseTime - offD * 24 * 3600 * 1000).toISOString();
    } else {
      const offD = v.offset_days || 18;
      publishedAt = new Date(baseTime - offD * 24 * 3600 * 1000).toISOString();
    }

    return {
      ...v,
      published_at: publishedAt,
      fetched_at: new Date(baseTime - 5 * 60 * 1000).toISOString(),
    };
  });
}

