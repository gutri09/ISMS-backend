function applyRollingTimestamps(clusters, baseTime = Date.now()) {
  return clusters.map((cluster) => {
    let firstPublished;
    let lastUpdated;

    if (cluster.target_periods.includes('24h')) {
      const ageH = cluster.age_hours || 4;
      firstPublished = new Date(baseTime - ageH * 3600 * 1000).toISOString();
      lastUpdated = new Date(baseTime - Math.max(12, ageH * 0.2 * 60) * 60 * 1000).toISOString();
    } else if (cluster.target_periods.includes('7d')) {
      const ageD = cluster.age_days || 3;
      firstPublished = new Date(baseTime - ageD * 24 * 3600 * 1000).toISOString();
      lastUpdated = new Date(baseTime - (2 + (cluster.rank % 4) * 2) * 3600 * 1000).toISOString();
    } else {
      const ageD = cluster.age_days || 20;
      firstPublished = new Date(baseTime - ageD * 24 * 3600 * 1000).toISOString();
      lastUpdated = new Date(baseTime - (12 + (cluster.rank % 6) * 4) * 3600 * 1000).toISOString();
    }

    const updatedArticles = (cluster.articles || []).map((art, idx) => {
      let publishedAt;
      if (cluster.target_periods.includes('24h')) {
        const offH = art.offset_hours || (idx + 1) * 1.5;
        publishedAt = new Date(baseTime - offH * 3600 * 1000).toISOString();
      } else if (cluster.target_periods.includes('7d')) {
        const offD = art.offset_days || (idx + 1) * 1.2;
        publishedAt = new Date(baseTime - offD * 24 * 3600 * 1000).toISOString();
      } else {
        const offD = art.offset_days || (idx + 1) * 6;
        publishedAt = new Date(baseTime - offD * 24 * 3600 * 1000).toISOString();
      }

      return {
        ...art,
        published_at: publishedAt,
        fetched_at: new Date(baseTime - 10 * 60 * 1000).toISOString(),
      };
    });

    return {
      ...cluster,
      first_published_at: firstPublished,
      last_updated_at: lastUpdated,
      articles: updatedArticles,
    };
  });
}

